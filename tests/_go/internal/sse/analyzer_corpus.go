func TestAnalyzerClassificationCorpus(t *testing.T) {
	got := make(map[string]corpusClassification, len(analyzerCorpus))
	for _, tc := range analyzerCorpus {
		if _, duplicate := got[tc.name]; duplicate {
			t.Fatalf("duplicate corpus case %q", tc.name)
		}
		got[tc.name] = classifyCorpus(tc.lines)
	}
	if analyzerCorpusGolden == "" {
		t.Fatal("golden classification missing")
	}
	var want map[string]corpusClassification
	if err := json.Unmarshal([]byte(analyzerCorpusGolden), &want); err != nil {
		t.Fatalf("golden classification is invalid: %v", err)
	}
	if len(want) != len(got) {
		t.Fatalf("golden cases = %d, want %d", len(want), len(got))
	}
	for _, tc := range analyzerCorpus {
		if !reflect.DeepEqual(got[tc.name], want[tc.name]) {
			t.Errorf("%s classification changed\ngot:  %+v\nwant: %+v", tc.name, got[tc.name], want[tc.name])
		}
	}
}
