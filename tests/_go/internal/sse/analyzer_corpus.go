// corpusClassification is the observable classification state of one analyzed
// SSE conversation: the analyzer's accumulated counters plus the record Fill
// produces. It intentionally names every field Feed classifies (content,
// reasoning, tool calls, finish reason, usage, model/id, refusal,
// function_call, choices, Responses events, and in-band errors) so the corpus
// pins their wire semantics rather than internal helper shapes.
type corpusClassification struct {
	FirstToken      bool          `json:"first_token"`
	LastToken       bool          `json:"last_token"`
	FirstAnswer     bool          `json:"first_answer"`
	FirstReasoning  int64         `json:"first_reasoning"`
	Chunks          int64         `json:"chunks"`
	ToolChunks      int64         `json:"tool_chunks"`
	ToolCalls       int           `json:"tool_calls"`
	ToolNames       []string      `json:"tool_names"`
	FinishReason    string        `json:"finish_reason"`
	Terminated      bool          `json:"terminated"`
	Chatlike        bool          `json:"chatlike"`
	ResponsesStream bool          `json:"responses_stream"`
	Answerish       bool          `json:"answerish"`
	Model           string        `json:"model"`
	RequestID       string        `json:"request_id"`
	UsageRaw        string        `json:"usage_raw"`
	UsageChunk      string        `json:"usage_chunk"`
	Preview         string        `json:"preview"`
	ErrorType       string        `json:"error_type"`
	ErrorCode       string        `json:"error_code"`
	ErrorMsg        string        `json:"error_msg"`
	HasInBandError  bool          `json:"has_in_band_error"`
	Outcome         string        `json:"outcome"`
	RecordUsage     metrics.Usage `json:"record_usage"`
	GenTokens       int64         `json:"gen_tokens"`
	HadAnswer       bool          `json:"had_answer"`
	ProviderModel   string        `json:"provider_model"`
	ProviderID      string        `json:"provider_id"`
	RecordPreview   string        `json:"record_preview"`
	RecordCalls     int           `json:"record_calls"`
	RecordNames     []string      `json:"record_names"`
	RecordReason    int64         `json:"record_reasoning"`
	RecordChunks    int64         `json:"record_chunks"`
}

func classifyCorpus(lines []string) corpusClassification {
	var a Analyzer
	a.CapturePreview = true
	now := time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC)
	for _, line := range lines {
		a.Feed([]byte(line), now)
	}
	var rec metrics.Record
	a.Fill(&rec)
	c := corpusClassification{
		FirstToken:      !a.firstTokenAt.IsZero(),
		LastToken:       !a.lastTokenAt.IsZero(),
		FirstAnswer:     !a.firstAnswerAt.IsZero(),
		Chunks:          a.chunkCount,
		ToolChunks:      a.toolChunks,
		ToolCalls:       a.toolCalls(),
		ToolNames:       a.toolNames,
		FinishReason:    a.finishReason,
		Terminated:      a.Terminated(),
		Chatlike:        a.chatlike,
		ResponsesStream: a.responsesStream,
		Answerish:       a.answerishSeen,
		Model:           a.model,
		RequestID:       a.reqID,
		UsageRaw:        string(a.usage),
		UsageChunk:      string(a.usageChunk),
		Preview:         string(a.preview),
		ErrorType:       a.errType,
		ErrorCode:       a.errCode,
		ErrorMsg:        a.errMsg,
		HasInBandError:  a.HasInBandError(),
		Outcome:         a.OutcomeCode(),
		RecordUsage:     rec.Usage,
		GenTokens:       rec.GenTokens,
		HadAnswer:       rec.HadAnswerContent,
		ProviderModel:   rec.ProviderModel,
		ProviderID:      rec.ProviderRequestID,
		RecordPreview:   rec.ResponsePreview,
		RecordCalls:     rec.ToolCalls,
		RecordNames:     rec.ToolNames,
		RecordReason:    rec.FirstReasoningAt,
		RecordChunks:    rec.Chunks,
	}
	if !a.firstReasoningAt.IsZero() {
		c.FirstReasoning = a.firstReasoningAt.UnixMilli()
	}
	return c
}

