"""Render the gallery page and its plate chrome from the capture registry.

The page is a generated document, not a hand-maintained one: it lists every
registered plate in reading order, with one caption that names the plate and
one description. The site's plate renderer reads the same registry and adds
the instrument chrome, so the Markdown page, the published page, the README
contact sheet and the manifest cannot disagree about what was captured.
"""
from __future__ import annotations

import argparse
from datetime import datetime
from html import escape
from pathlib import Path

from . import GALLERY, manifest
from .model import ROOT

PAGE = ROOT / "docs/gallery.md"
GENERATED_BY = "python3 -m scripts.gallery.render --write"


def _date(stamp: str) -> str:
    moment = datetime.fromisoformat(stamp)
    return f"{moment.day} {moment:%B %Y}"


def page(document: dict) -> str:
    plates = len(GALLERY.plates)
    stations = len(GALLERY.stations)
    records = format(document["source_records"], ",")
    parts = [
        "# Capture gallery",
        "",
        f"<!-- Generated by {GENERATED_BY} from scripts/gallery/data.py and",
        "     docs/images/capture.json. Do not edit. -->",
        "",
        f"{plates} plates across {stations} stations, captured "
        f"{_date(document['captured_at'])} UTC from {records} recorded requests "
        "with identifiers replaced and content removed.",
        "",
        "Every plate is one state photographed on both primary surfaces and "
        "split along the diagonal from the bottom-left corner to the top-right. "
        "The upper-left half is Instrument Black, the lower-right half is "
        "Instrument Clear. Nothing else changes between the halves: the same "
        "data, the same scroll, the same open surface.",
        "",
        "Values are a static sample from recorded history, not a benchmark. "
        "The offline indicator describes the capture session.",
        "",
    ]
    for number, station, members in GALLERY.ordered():
        parts.extend([f"## {station.title}", "", station.lede, ""])
        for plate in members:
            index = GALLERY.number(plate)
            caption = (f"<strong>{index:02d} · {escape(plate.title)}</strong> "
                       f"{escape(plate.note)}")
            parts.extend([
                "<figure>",
                f'<img src="{plate.path}" alt="{escape(plate.alt, quote=True)}">',
                f"<figcaption>{caption}</figcaption>",
                "</figure>",
                "",
            ])
    return "\n".join(parts).rstrip() + "\n"


def write_page(document: dict | None = None) -> None:
    PAGE.write_text(page(document or manifest.read()), encoding="utf-8")


def check() -> list[str]:
    try:
        expected = page(manifest.read())
    except (OSError, ValueError, KeyError) as error:
        return [f"cannot render the gallery page: {error}"]
    if not PAGE.is_file():
        return [f"{PAGE.relative_to(ROOT)} is missing; run {GENERATED_BY}"]
    if PAGE.read_text(encoding="utf-8") != expected:
        return [f"{PAGE.relative_to(ROOT)} is stale; run {GENERATED_BY}"]
    return []


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.write:
        write_page()
        print(f"wrote {PAGE.relative_to(ROOT)}")
        return 0
    errors = check()
    for error in errors:
        print("gallery: " + error)
    if not errors:
        print("gallery: clean")
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
