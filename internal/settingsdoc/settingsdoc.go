// Package settingsdoc renders docs/settings.md, the one reference page that
// lists every user-tunable setting and every proxy CLI flag.
//
// Every fact on the page has one owner in the code: internal/config.Schema()
// owns the key, label, type, bound, closed vocabulary, reload behavior and
// help; config.Default() owns every default, rendered through the canonical
// YAML writer so a default is spelled exactly as proxy.example.yaml spells it;
// and the flag registrations in cmd/proxy own the CLI rows, discovered by
// parsing that file rather than by keeping a second list here.
package settingsdoc

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"github.com/LLM-4-People/millivolt/internal/atomicfile"
	"github.com/LLM-4-People/millivolt/internal/config"
)

// PagePath is the generated page, relative to the module root.
const PagePath = "docs/settings.md"

// writeCommand is the one command that renders the page. Every stale-page
// report names it, so the fix is always in the failure message.
const writeCommand = "go run ./cmd/docgen -write"

// proxyMain is the file whose flag registrations own the CLI section.
const proxyMain = "cmd/proxy/main.go"

// Render returns the complete generated page for the repository rooted at
// root. Nothing is read from the page itself: every cell is derived from the
// owners above, so a page that disagrees with the code is drift.
func Render(root string) ([]byte, error) {
	defaults, err := defaultSpellings()
	if err != nil {
		return nil, err
	}
	flags, err := Flags(root)
	if err != nil {
		return nil, err
	}
	return render(defaults, flags)
}

// Flag is one proxy CLI flag, as its registration declares it.
type Flag struct {
	Name    string
	Type    string
	Default string
	Usage   string
}

func render(defaults map[string]string, flags []Flag) ([]byte, error) {
	var b strings.Builder
	b.WriteString("# Settings reference\n\n")
	b.WriteString("<!-- Generated by cmd/docgen from internal/config.Schema(), config.Default()\n")
	b.WriteString("     and the proxy flag registration. Do not edit: run `" + writeCommand + "`\n")
	b.WriteString("     after changing one of those owners. -->\n\n")
	b.WriteString("Settings and the proxy CLI write the same fields. The dashboard Settings sheet\n")
	b.WriteString("saves them through `GET` and `POST /admin/config`, the YAML file holds them at\n")
	b.WriteString("rest, and the proxy flags override a few of them at launch. Every block below\n")
	b.WriteString("is generated from the code that owns it, so a setting's key, label, type,\n")
	b.WriteString("bound, reload behavior and help cannot describe one thing here and another in\n")
	b.WriteString("the dashboard. A `-` under accepted values means the schema declares no bound\n")
	b.WriteString("and no closed vocabulary for that key.\n\n")
	b.WriteString("Read [configuration](configuration.md) for precedence, the YAML file and the\n")
	b.WriteString("settings schema, and [containers](containers.md) for image mounts, restore\n")
	b.WriteString("paths and the deployment lifecycle.\n\n")

	byCategory := make(map[string][]config.Field, len(config.Categories()))
	for _, field := range config.Schema() {
		byCategory[field.Category] = append(byCategory[field.Category], field)
	}
	for _, category := range config.Categories() {
		fields := byCategory[category.ID]
		if len(fields) == 0 {
			continue
		}
		b.WriteString("## " + category.Label + "\n\n")
		if category.Help != "" {
			help, err := prose(category.ID, category.Help)
			if err != nil {
				return nil, err
			}
			b.WriteString(help + "\n\n")
		}
		for _, field := range fields {
			block, err := settingBlock(field, defaults)
			if err != nil {
				return nil, err
			}
			b.WriteString(block)
		}
	}

	b.WriteString("## Proxy CLI flags\n\n")
	b.WriteString("The flag set in `cmd/proxy` owns these blocks. Every flag is parsed before any\n")
	b.WriteString("configuration is loaded, so the default below is the registration default, not\n")
	b.WriteString("the effective value after a config file or another override.\n\n")
	for _, flag := range flags {
		block, err := flagBlock(flag)
		if err != nil {
			return nil, err
		}
		b.WriteString(block)
	}
	return []byte(b.String()), nil
}

// settingBlock renders one schema field as a readable block: the key, label
// and type on one line, the compact facts on the next, then the help at full
// width. A long structured default moves into a fenced block instead of
// forcing a table column wider than the page.
func settingBlock(field config.Field, defaults map[string]string) (string, error) {
	def, ok := defaults[field.Key]
	if !ok {
		return "", fmt.Errorf("schema key %q has no rendered default: the YAML writer did not emit it", field.Key)
	}
	keyCell, err := code(field.Key+" key", field.Key)
	if err != nil {
		return "", err
	}
	typeCell, err := code(field.Key+" type", typeName(field))
	if err != nil {
		return "", err
	}
	label, err := prose(field.Key+" label", field.Label)
	if err != nil {
		return "", err
	}
	accepted, err := acceptedValues(field)
	if err != nil {
		return "", err
	}
	help, err := prose(field.Key+" help", field.Help)
	if err != nil {
		return "", err
	}
	reload := "Restart required"
	if field.HotReload {
		reload = "Hot-reloads"
	}
	var b strings.Builder
	b.WriteString("#### " + keyCell + "\n\n" + label + " · " + typeCell + "\n\n")
	if longDefault(def) {
		b.WriteString("Default:\n\n```yaml\n" + strings.TrimRight(def, "\n") + "\n```\n\n")
	} else {
		defaultCell, err := code(field.Key+" default", def)
		if err != nil {
			return "", err
		}
		b.WriteString("Default " + defaultCell + " · ")
	}
	b.WriteString("Accepted " + accepted + " · " + reload + "\n\n")
	b.WriteString(helpParagraphs(help) + "\n\n")
	return b.String(), nil
}

// flagBlock renders one proxy flag in the same shape as a setting.
func flagBlock(flag Flag) (string, error) {
	keyCell, err := code("-"+flag.Name+" key", "-"+flag.Name)
	if err != nil {
		return "", err
	}
	typeCell, err := code("-"+flag.Name+" type", flag.Type)
	if err != nil {
		return "", err
	}
	defaultCell, err := code("-"+flag.Name+" default", flag.Default)
	if err != nil {
		return "", err
	}
	usage, err := prose("-"+flag.Name+" usage", flag.Usage)
	if err != nil {
		return "", err
	}
	return "#### " + keyCell + "\n\n" + typeCell + "\n\nDefault " + defaultCell +
		"\n\n" + helpParagraphs(usage) + "\n\n", nil
}

// longDefault keeps a structured YAML default out of the compact fact line.
// The threshold is presentation only; the value still comes from the one YAML
// writer and is compared byte-for-byte by the config suite.
func longDefault(value string) bool {
	return len(value) > 80 || strings.Contains(value, "\n")
}

// helpParagraphs keeps a long owner sentence set scannable. It splits after
// sentence punctuation and groups sentences into paragraphs of at most 85
// words. Words and punctuation are untouched; only whitespace changes.
func helpParagraphs(text string) string {
	words := strings.Fields(text)
	if len(words) <= 85 {
		return text
	}
	var paragraphs []string
	var current []string
	count := 0
	for _, sentence := range splitSentences(text) {
		n := len(strings.Fields(sentence))
		if count > 0 && count+n > 85 {
			paragraphs = append(paragraphs, strings.Join(current, " "))
			current = current[:0]
			count = 0
		}
		current = append(current, sentence)
		count += n
	}
	if len(current) > 0 {
		paragraphs = append(paragraphs, strings.Join(current, " "))
	}
	return strings.Join(paragraphs, "\n\n")
}

var sentenceEnd = regexp.MustCompile(`[.!?]\s+`)

func splitSentences(text string) []string {
	var out []string
	start := 0
	for _, match := range sentenceEnd.FindAllStringIndex(text, -1) {
		end := match[0] + 1
		out = append(out, strings.TrimSpace(text[start:end]))
		start = match[1]
	}
	out = append(out, strings.TrimSpace(text[start:]))
	return out
}

// typeName is the UI/API type the dashboard renders a control from, with the
// unit the schema labels a bare integer with (tokens, percent).
func typeName(field config.Field) string {
	name := string(field.Kind)
	if field.Kind == config.KindInt && field.Unit != "" {
		name += " (" + field.Unit + ")"
	}
	return name
}

// acceptedValues renders the closed vocabulary or the bound the schema
// declares. Both owners already live on the field, so the cell cannot invent
// a limit: when the schema declares neither, the cell is a dash.
func acceptedValues(field config.Field) (string, error) {
	var parts []string
	if len(field.Choices) > 0 {
		choices := make([]string, 0, len(field.Choices))
		for _, choice := range field.Choices {
			cell, err := code(field.Key+" choice", choice)
			if err != nil {
				return "", err
			}
			choices = append(choices, cell)
		}
		parts = append(parts, strings.Join(choices, ", "))
	}
	if rangeText := field.RangeText(); rangeText != "" {
		parts = append(parts, rangeText)
	}
	if len(parts) == 0 {
		return "-", nil
	}
	return strings.Join(parts, ", "), nil
}

// prose validates one owner sentence before it reaches the page. A line break
// would break the block shape, and an odd backtick would open a code span that
// swallows the rest of the paragraph, so both fail loudly instead.
func prose(owner, text string) (string, error) {
	if strings.ContainsAny(text, "\r\n") {
		return "", fmt.Errorf("%s: text contains a line break", owner)
	}
	if strings.Count(text, "`")%2 != 0 {
		return "", fmt.Errorf("%s: text carries an unbalanced backtick", owner)
	}
	return text, nil
}

// code escapes one literal value and wraps it in a code span. A value that
// itself contains a backtick cannot be rendered inline without changing it.
func code(owner, text string) (string, error) {
	if strings.Contains(text, "`") {
		return "", fmt.Errorf("%s: value %q contains a backtick", owner, text)
	}
	if strings.ContainsAny(text, "\r\n") {
		return "", fmt.Errorf("%s: value %q contains a line break", owner, text)
	}
	return "`" + strings.ReplaceAll(text, "|", `\|`) + "`", nil
}

// flagShapes maps a flag registration function to the flag type and the
// position of its name, default and usage arguments. The *Var forms take the
// destination pointer first.
var flagShapes = map[string]struct {
	kind       string
	nameArg    int
	defaultArg int
	usageArg   int
}{
	"String":      {"string", 0, 1, 2},
	"Bool":        {"bool", 0, 1, 2},
	"Int":         {"int", 0, 1, 2},
	"Int64":       {"int", 0, 1, 2},
	"Uint":        {"int", 0, 1, 2},
	"Uint64":      {"int", 0, 1, 2},
	"Float64":     {"float", 0, 1, 2},
	"Duration":    {"duration", 0, 1, 2},
	"StringVar":   {"string", 1, 2, 3},
	"BoolVar":     {"bool", 1, 2, 3},
	"IntVar":      {"int", 1, 2, 3},
	"Int64Var":    {"int", 1, 2, 3},
	"UintVar":     {"int", 1, 2, 3},
	"Uint64Var":   {"int", 1, 2, 3},
	"Float64Var":  {"float", 1, 2, 3},
	"DurationVar": {"duration", 1, 2, 3},
}

// Flags discovers the proxy's flags from its registration calls. The walk is
// deny by default: every flag.* selector in the file must be either flag.Parse
// or one recognized registration, so a registration shape this renderer does
// not understand fails instead of disappearing from the page.
func Flags(root string) ([]Flag, error) {
	path := filepath.Join(root, proxyMain)
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("parse proxy flag registration: %w", err)
	}
	var flags []Flag
	var findErr error
	ast.Inspect(file, func(node ast.Node) bool {
		if findErr != nil {
			return false
		}
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return true
		}
		selector, ok := call.Fun.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		pkg, ok := selector.X.(*ast.Ident)
		if !ok || pkg.Name != "flag" {
			return true
		}
		if selector.Sel.Name == "Parse" {
			return true
		}
		shape, ok := flagShapes[selector.Sel.Name]
		if !ok {
			findErr = fmt.Errorf("%s: unsupported flag registration flag.%s; teach internal/settingsdoc about it",
				fset.Position(call.Pos()), selector.Sel.Name)
			return false
		}
		if want := shape.usageArg + 1; len(call.Args) != want {
			findErr = fmt.Errorf("%s: flag.%s takes %d arguments, found %d",
				fset.Position(call.Pos()), selector.Sel.Name, want, len(call.Args))
			return false
		}
		name, err := literalString(call.Args[shape.nameArg])
		if err != nil {
			findErr = fmt.Errorf("%s: flag name: %w", fset.Position(call.Args[shape.nameArg].Pos()), err)
			return false
		}
		def, err := literalDefault(call.Args[shape.defaultArg])
		if err != nil {
			findErr = fmt.Errorf("%s: flag -%s default: %w", fset.Position(call.Args[shape.defaultArg].Pos()), name, err)
			return false
		}
		usage, err := literalString(call.Args[shape.usageArg])
		if err != nil {
			findErr = fmt.Errorf("%s: flag -%s usage: %w", fset.Position(call.Args[shape.usageArg].Pos()), name, err)
			return false
		}
		flags = append(flags, Flag{Name: name, Type: shape.kind, Default: def, Usage: usage})
		return true
	})
	if findErr != nil {
		return nil, findErr
	}
	if len(flags) == 0 {
		return nil, fmt.Errorf("%s declares no proxy flag: the CLI section would be empty", path)
	}
	return flags, nil
}

// literalString returns the value of a string literal argument.
func literalString(expr ast.Expr) (string, error) {
	lit, ok := expr.(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return "", fmt.Errorf("want a string literal, found %T", expr)
	}
	value, err := strconv.Unquote(lit.Value)
	if err != nil {
		return "", err
	}
	return value, nil
}

// literalDefault returns the spelling of a flag's registered default: a string
// default keeps its quoting so an empty string stays visible, and a boolean
// default is its Go literal.
func literalDefault(expr ast.Expr) (string, error) {
	if lit, ok := expr.(*ast.BasicLit); ok {
		switch lit.Kind {
		case token.STRING, token.INT, token.FLOAT:
			return lit.Value, nil
		}
		return "", fmt.Errorf("want a string, number or boolean literal, found %s", lit.Value)
	}
	if ident, ok := expr.(*ast.Ident); ok && (ident.Name == "true" || ident.Name == "false") {
		return ident.Name, nil
	}
	return "", fmt.Errorf("want a literal default, found %T", expr)
}

// keyLine matches one top-level key of the generated YAML document.
var keyLine = regexp.MustCompile(`^([a-z][a-z0-9_]*):(.*)$`)

// defaultSpellings renders config.Default() through the canonical YAML writer
// and returns each top-level key's value on one line. Reusing the writer is the
// point: a duration, byte size, list or map default is spelled exactly as the
// YAML file and the Settings sheet spell it, instead of being formatted a
// second time here.
func defaultSpellings() (map[string]string, error) {
	var buf bytes.Buffer
	if err := config.WriteYAML(&buf, config.Default()); err != nil {
		return nil, fmt.Errorf("render default config: %w", err)
	}
	values, err := topLevelValues(buf.String())
	if err != nil {
		return nil, err
	}
	for _, field := range config.Schema() {
		if _, ok := values[field.Key]; !ok {
			return nil, fmt.Errorf("schema key %q is missing from the rendered default config", field.Key)
		}
	}
	return values, nil
}

// topLevelValues splits the writer's document into one collapsed value per
// top-level key. Comment lines belong to the documented example, not to a
// value, so they are skipped.
func topLevelValues(document string) (map[string]string, error) {
	values := map[string]string{}
	key := ""
	var parts []string
	flush := func() {
		if key == "" {
			return
		}
		values[key] = strings.Join(strings.Fields(strings.Join(parts, " ")), " ")
	}
	for _, line := range strings.Split(document, "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if match := keyLine.FindStringSubmatch(line); match != nil {
			flush()
			key = match[1]
			parts = []string{match[2]}
			continue
		}
		if key == "" {
			return nil, fmt.Errorf("generated config: %q appears before any top-level key", line)
		}
		if line[0] != ' ' && line[0] != '\t' {
			return nil, fmt.Errorf("generated config: %q continues key %q without indentation", line, key)
		}
		parts = append(parts, line)
	}
	flush()
	return values, nil
}

// Mismatch is the first byte-for-byte difference between the page on disk and
// a fresh render.
type Mismatch struct {
	Line      int    // 1-based line of the first difference
	Page      string // the page's line, empty when the page ends first
	Generated string // the freshly rendered line, empty when it ends first
}

// Error names the first stale line and the command that rewrites the page.
func (m *Mismatch) Error() string {
	return fmt.Sprintf("%s:%d: generated settings reference is stale\n  page:      %q\n  generated: %q\nrun: %s",
		PagePath, m.Line, m.Page, m.Generated, writeCommand)
}

// Check re-renders the page in memory and compares it byte for byte with the
// file on disk. It returns nil when the file is exactly the current render, the
// first differing line when it is stale, and an error when it cannot be read or
// rendered.
func Check(root string) error {
	page, err := os.ReadFile(filepath.Join(root, PagePath))
	if err != nil {
		return fmt.Errorf("%s: %w; run: %s", PagePath, err, writeCommand)
	}
	generated, err := Render(root)
	if err != nil {
		return err
	}
	if bytes.Equal(page, generated) {
		return nil
	}
	return firstDifference(page, generated)
}

// firstDifference reports the first line where page and generated disagree.
func firstDifference(page, generated []byte) *Mismatch {
	pageLines := strings.Split(string(page), "\n")
	generatedLines := strings.Split(string(generated), "\n")
	for index := 0; index < len(pageLines) || index < len(generatedLines); index++ {
		var pageLine, generatedLine string
		if index < len(pageLines) {
			pageLine = pageLines[index]
		}
		if index < len(generatedLines) {
			generatedLine = generatedLines[index]
		}
		if pageLine != generatedLine {
			return &Mismatch{Line: index + 1, Page: pageLine, Generated: generatedLine}
		}
	}
	return &Mismatch{Line: 1}
}

// Write atomically replaces the page with a fresh render.
func Write(root string) error {
	page, err := Render(root)
	if err != nil {
		return err
	}
	return atomicfile.WriteFile(filepath.Join(root, PagePath), page, 0o644)
}
